// convert 250 into string using String.valueOf() 
// convert "123" into integer using integer.parseint() and add 7

package Strings;

public class Ques7 {

    public static void main(String[] args) {
        // Convert 250 into String
        String s = String.valueOf(250);
        System.out.println(s);

        // Convert "123" into integer and add 7
        
        int n = Integer.parseInt("123");
        System.out.println(n + 7);
    }
}
